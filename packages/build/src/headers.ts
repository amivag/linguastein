/**
 * The response headers a host with header control should send: Cloudflare's
 * `_headers` file format, written next to the build.
 *
 * The content security policy is the same one the build puts in a `<meta>`
 * (`csp.ts`), plus `frame-ancestors`, which only a header can carry. Both stay:
 * the meta still protects a copy of the build served from a host without headers.
 *
 * Deliberately absent, because each depends on a decision not yet made:
 * - `Strict-Transport-Security` belongs to the domain. Set it in the domain's
 *   settings once one is chosen; `includeSubDomains` commits every future app.
 * - `Cross-Origin-Embedder-Policy` turns on cross-origin isolation, which only an
 *   app needing `SharedArrayBuffer` (audio or WebAssembly threads) has a use for.
 *   It also blocks any cross-origin embed that does not opt in.
 */

import { contentSecurityPolicy } from './csp.ts';

/** Browser features an app may ask for; each is denied unless the app allows it. */
export const PERMISSIONS = [
  'microphone',
  'camera',
  'geolocation',
  'payment',
  'usb',
  'screen-wake-lock',
] as const;
export type Permission = (typeof PERMISSIONS)[number];

export interface HeaderOptions {
  /** The app's base path, with a leading and a trailing slash. */
  readonly basePath: string;
  /** Features this app uses. Everything else in {@link PERMISSIONS} is denied. */
  readonly allow?: readonly Permission[];
  /** Whether search engines may index it. Keep in step with the page's robots meta. */
  readonly indexable?: boolean;
}

export function cloudflareHeaders(
  html: string,
  { basePath, allow = [], indexable = false }: HeaderOptions,
): string {
  const permissions = PERMISSIONS.map(
    (name) => `${name}=${allow.includes(name) ? '(self)' : '()'}`,
  ).join(', ');
  const all = [
    `Content-Security-Policy: ${contentSecurityPolicy(html)}; frame-ancestors 'none'`,
    'X-Content-Type-Options: nosniff',
    'Referrer-Policy: strict-origin-when-cross-origin',
    'Cross-Origin-Opener-Policy: same-origin',
    'Cross-Origin-Resource-Policy: same-origin',
    `Permissions-Policy: ${permissions}`,
    ...(indexable ? [] : ['X-Robots-Tag: noindex, nofollow, noarchive']),
  ];

  return [
    '# Generated by the build (@platform/build). Do not edit.',
    '/*',
    ...all.map((line) => `  ${line}`),
    '',
    // Content-hashed file names: a changed file is a new URL.
    `${basePath}assets/*`,
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    // Never cached past a revalidation: it decides which build the person gets.
    `${basePath}sw.js`,
    '  Cache-Control: no-cache',
    '',
  ].join('\n');
}
